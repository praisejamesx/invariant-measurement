"""
Aggregate experiment outputs into the tables used by the paper.

Every number in paper/draft.md should come from one of the CSVs read here.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from experiments.common import RESULTS

ROOT = RESULTS


def fmt(df, cols=None, floatfmt="{:.3f}"):
    if cols:
        df = df[cols]
    return df.to_markdown(index=False, floatfmt=floatfmt)


def main():
    lines = ["# Key results (generated by experiments/aggregate.py)", ""]

    # ---------------- MOX ----------------
    mox = pd.read_csv(ROOT / "mox/e1_transfer.csv")
    pooled = mox[mox.target_batch == "pooled"].copy()
    pooled = pooled.sort_values("accuracy", ascending=False)
    lines += ["## MOX: UCI drift, train on batch 1", "",
              "Pooled accuracy over batches 2-10.", "",
              fmt(pooled, ["feature", "accuracy", "balanced_accuracy", "macro_f1"]), ""]
    per_batch = mox[mox.target_batch != "pooled"].pivot_table(
        index="target_batch", columns="feature", values="accuracy")
    keep = ["raw", "log", "global_gain", "selectivity", "batch_center",
            "calibrated_5pc"]
    keep = [k for k in keep if k in per_batch.columns]
    lines += ["Per-batch accuracy (selected features):", "",
              per_batch[keep].round(3).to_markdown(), ""]

    gs = pd.read_csv(ROOT / "mox/e2_group_stress.csv")
    lines += ["Controlled group-stress test (batch 1, transformed test half):", "",
              gs.pivot_table(index="group", columns="feature",
                             values="mean_accuracy").round(3).to_markdown(), ""]

    stab = pd.read_csv(ROOT / "mox/e3_slope_stability.csv")
    lines += ["Stability of gas-level slope ratios across batches:", "",
              fmt(stab), ""]

    # ---------------- NIR ----------------
    nir = pd.read_csv(ROOT / "nir_corn/n2_transfer.csv")
    nir = nir[nir.property == "Protein"]
    nir["pair"] = nir.source + "->" + nir.target
    tab = nir.pivot_table(index="pair", columns="representation",
                          values="r2_mean")
    lines += ["## NIR: Corn, protein, train on source instrument", "",
              "Cells are mean test R² over reference sets; instrument B is never labelled.", "",
              tab.round(3).to_markdown(), ""]

    within = pd.read_csv(ROOT / "nir_corn/n1_within_cv.csv")
    lines += ["Within-instrument 5-fold CV (protein):", "",
              within.pivot_table(index="instrument", columns="representation",
                                 values="cv_r2").round(3).to_markdown(), ""]

    gf = pd.read_csv(ROOT / "nir_corn/n1_group_fit.csv")
    lines += ["Oracle group-model fit (all samples used to estimate the group):", "",
              fmt(gf), ""]

    ref = pd.read_csv(ROOT / "nir_corn/n3_reference_scaling.csv")
    lines += ["Reference-count scaling (m5->mp5, protein):", "",
              ref.pivot_table(index="n_references", columns="representation",
                              values="r2_mean").round(3).to_markdown(), ""]

    anch = pd.read_csv(ROOT / "nir_corn/n4_anchor_sensitivity.csv")
    cond = anch[anch.conditioned]
    lines += ["Anchor conditioning (m5->mp5, protein):", "",
              f"- random pairs median R²: {anch.r2.median():.3f}",
              f"- random pairs 75th percentile R²: {anch.r2.quantile(0.75):.3f}",
              f"- conditioned pair R²: {cond.r2.iloc[0]:.3f}",
              f"- conditioning-score / R² Pearson r: {anch.conditioning_score.corr(anch.r2):.3f}", ""]

    # ---------------- EEG / Raman / microscopy / MS / sequencing ----------------
    for name, title in [
        ("eeg", "EEG (real signal, synthetic transforms)"),
        ("raman", "Raman (real spectra, synthetic transforms)"),
        ("microscopy", "Microscopy (real image, synthetic illumination)"),
        ("massspec", "Mass spec (synthetic)"),
        ("sequencing", "Sequencing (real genome, simulated reads)"),
    ]:
        p = ROOT / name / "summary.json"
        if p.exists():
            import json
            d = json.load(open(p))
            lines += [f"## {title}", "", "```json", json.dumps(d, indent=2)[:4000], "```", ""]

    (ROOT / "summary.md").write_text("\n".join(lines))
    print(f"wrote {ROOT / 'summary.md'}")


if __name__ == "__main__":
    main()
